export type AbilityStyle = 'melee' | 'ranged' | 'magic' | 'necromancy' | 'defence' | 'constitution';
export type AbilityType = 'Basic' | 'Enhanced' | 'Threshold' | 'Ultimate' | 'Utility' | 'Special';
export type AbilityTarget = 'Self' | 'Single' | 'Area' | 'Multi' | 'Varies';

export interface Ability {
	name: string;
	style: AbilityStyle;
	/** The skill this ability's level requirement is measured in -- almost always the same
	 *  skill as `style`, except a handful of cross-skill requirements (e.g. Dive requires
	 *  Agility, not Attack). */
	requiredSkill: string;
	requiredLevel: number;
	type: AbilityType;
	/** Adrenaline as a percentage: positive means the ability GENERATES this much (Basic
	 *  abilities, e.g. 9 or 12), negative means it COSTS this much and requires at least
	 *  that much banked to cast (Enhanced/Threshold/Ultimate, e.g. -15 to -100). Verified
	 *  against the actual scraped values -- this is the opposite of how it might first read. */
	adrenaline: number;
	target: AbilityTarget;
	/**
	 * Damage as a percentage of "normal" ability damage (the value calculateAbilityDamage()
	 * computes), e.g. 250 for Overpower's 250%. A range like "90%-110%" is kept as the raw
	 * string. null for abilities with no single damage value -- either non-damaging (target
	 * is 'Self') or equipment-dependent (see damageVariants).
	 */
	damagePercent: string | null;
	/**
	 * For abilities whose damage percentage depends on equipped gear (e.g. Adaptive Strike:
	 * different % for dual wield vs two-handed vs main-hand-only; Overpower/Deadshot/
	 * Omnipower/Asphyxiate/Death Skulls: boosted by a specific igneous cape or Tumeken's
	 * resplendence set), a dictionary from an equipment description to that setup's damage
	 * percentage. Index into this using the player's current loadout to find the right
	 * value. null for abilities with one fixed damagePercent instead.
	 */
	damageVariants: Record<string, string> | null;
	/**
	 * For abilities whose HIT COUNT (not just total damage) depends on equipped gear -- currently
	 * just the four igneous-cape ultimates (Overpower/Omnipower/Deadshot/Death Skulls: hitting more,
	 * smaller-damage times when the matching igneous cape is worn). Keyed exactly like
	 * `damageVariants` (equipment description -> value), indexed the same way via
	 * `resolveDamagePercent`'s gear-matching logic. null for abilities whose hit count doesn't vary
	 * by gear -- including ones that still have gear-dependent damageVariants for other reasons
	 * (e.g. Adaptive Strike's dual-wield/two-handed damage split doesn't change its hit count).
	 */
	hitCountVariants: Record<string, number> | null;
	/** Raw cooldown text as scraped, e.g. "20.4 seconds (34 ticks)" or "N/A". */
	cooldownText: string;
	/** Equipment requirement/note, e.g. "Two-handed", "None", or a description of which
	 *  variant this entry represents when damageVariants is set. */
	equipment: string;
	description: string;
	membersOnly: boolean;
	/** Path under /ability-icons relative to the static root. */
	iconPath: string;
	/** For per-weapon special attacks (type 'Special', excluding the generic "Weapon Special
	 *  Attack"/"Essence of Finality" entries): the weapon(s) that trigger this exact special
	 *  attack, e.g. ["Dragon dagger", "Superior dragon dagger"] both trigger "Draconic
	 *  Puncture". null for all other abilities. */
	weapons: string[] | null;

	// --- Typed mechanic fields (optional migration target) ---
	// These mirror what timeline.ts's parseX functions currently derive from `description` via
	// regex. Each one is optional and, while unset, every ability falls back to the legacy
	// regex parse -- so this is a zero-risk, incremental migration surface: set a field here
	// once an ability's mechanic has been hand-verified against the wiki, and the corresponding
	// parseX function in timeline.ts will prefer it over re-deriving from text. See `verified`
	// below for the actual completeness signal shown to the user; these fields are what gets
	// checked off as part of reaching that state, not a signal by themselves.

	/** True if usable during the GCD, false if not. Mirrors isOffGcdAbility's regex. Leave
	 *  unset to fall back to parsing `description`. */
	offGcd?: boolean;
	/** Mirrors parseHitProfile's regex-derived HitProfile (see timeline.ts). Leave unset to
	 *  fall back to parsing `description`. */
	hitProfile?: { kind: 'single' } | { kind: 'channel'; hits: number; intervalTicks: number; isBleed: boolean };
	/** Mirrors parseBuffInfo's regex-derived duration. null means "confirmed this ability is
	 *  NOT a self-buff" (a real, verified negative) -- distinct from leaving the field unset,
	 *  which means "unverified, fall back to parsing `description`". */
	buffProfile?: { durationTicks: number } | null;
	/** Mirrors parseBuffExtension's regex-derived buff-extension clause. null means "confirmed
	 *  this ability does NOT extend any buff". Unset falls back to parsing `description`. */
	buffExtension?: { buffDisplayName: string; extendTicks: number } | null;
	/** For a 'single'-profile ability whose hits land on more than just its own placement tick
	 *  (e.g. Ricochet: 3 hits total, but only the first lands immediately -- the other two land
	 *  1 tick later), the tick OFFSET from the placement's startTick for each hit, one entry per
	 *  hit -- e.g. Ricochet is `[0, 1, 1]`. Has no effect on a 'channel'-profile ability, which
	 *  already has its own timing via `hitProfile.intervalTicks`. Unset means "every hit lands on
	 *  the placement's own startTick, offset 0" -- the same behavior every ability had before this
	 *  field existed, so leaving it unset is a safe, unverified default, not a fallback to regex
	 *  parsing (there's no description wording for this timing to parse in the first place).
	 *
	 *  A `Record` keyed exactly like `damageVariants`/`hitCountVariants` (e.g. 'Dual wield',
	 *  'Main hand, no offhand', 'Two-handed') is for abilities whose hit TIMING (not just damage or
	 *  hit count) itself differs by equipped weapon -- e.g. Adaptive Strike: a single hit at offset
	 *  0 for 2h/main-hand-only, but two simultaneous hits (`[0, 0]`) for dual wield. Resolved via
	 *  the same gear-matching logic as those two fields (see resolveDamagesOnTick/
	 *  resolveGearVariant in timeline.ts) -- reuse that convention rather than inventing new keys. */
	damagesOnTick?: number[] | Record<string, number[]>;

	/** Manual attestation that every mechanic this ability actually has has been hand-checked
	 *  against the wiki and (where relevant) backed by the typed fields above, rather than left
	 *  to the description-regex fallback. Defaults to unset/false for all scraped entries --
	 *  this is never inferred, only set by a human confirming the ability's behavior. Drives the
	 *  "not fully implemented" warning chip in Timeline.svelte. */
	verified?: boolean;
}

